import os

try:
    import docx
    from pptx import Presentation
    from pptx.util import Inches
    DOCS_ENABLED = True
except Exception:
    DOCS_ENABLED = False
    print("Warning: python-docx or python-pptx not available. Document generation will be disabled.")

def create_word_document(topic: str, content: str, output_path: str):
    """Generates a Word document with the given content."""
    if not DOCS_ENABLED:
        raise Exception("Document generation is not supported on this Python version.")
        
    doc = docx.Document()
    doc.add_heading(f'Topic: {topic}', 0)
    
    # Split content by paragraphs and add to document
    paragraphs = content.split('\n\n')
    for p in paragraphs:
        if p.strip():
            doc.add_paragraph(p.strip())
            
    doc.save(output_path)
    return output_path

def create_powerpoint_presentation(topic: str, content: str, output_path: str):
    """Generates a simple PowerPoint presentation based on content."""
    if not DOCS_ENABLED:
        raise Exception("Presentation generation is not supported on this Python version.")
        
    prs = Presentation()
    
    # Title Slide
    title_slide_layout = prs.slide_layouts[0]
    slide = prs.slides.add_slide(title_slide_layout)
    title = slide.shapes.title
    subtitle = slide.placeholders[1]
    
    title.text = topic
    subtitle.text = "Generated by OmniAI"
    
    # Content Slides (rough split)
    paragraphs = content.split('\n\n')
    bullet_slide_layout = prs.slide_layouts[1]
    
    for p in paragraphs:
        if p.strip():
            # If paragraph is too long, we just make it a single slide with bullet points
            slide = prs.slides.add_slide(bullet_slide_layout)
            shapes = slide.shapes
            title_shape = shapes.title
            body_shape = shapes.placeholders[1]
            
            title_shape.text = f"Key Point"
            
            tf = body_shape.text_frame
            tf.text = p.strip()

    prs.save(output_path)
    return output_path
